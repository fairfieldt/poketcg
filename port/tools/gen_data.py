#!/usr/bin/env python3
"""Generate the C port's game data from the disassembly and the built ROM.

Outputs (port/src/gen/):
  cards.c / cards.h            raw 0x41-byte card records exactly as LoadCardDataToHL copies them
  decks.c / decks.h            raw deck lists (DeckPointers) exactly as CopyDeckData reads them
  text.c / text.h              every string of TextOffsets, decoded to UTF-8 (TX_RAM* codes kept)
  effect_commands.c / .h       every effect command list of the "Effect Commands" section,
                               keyed by its original Game Boy address

Binary data is read from poketcg.gbc so it is byte-identical to the original;
names come from poketcg.sym. Run `make` at the repository root first.
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from romsym import Rom, ROOT

GEN = os.path.join(ROOT, 'port', 'src', 'gen')
HDR = '/* Generated by port/tools/gen_data.py. Do not edit. */\n'

def consts():
    vals = {}
    for line in open(os.path.join(GEN, 'constants.h')):
        m = re.match(r'#define (\w+) (0x[0-9a-f]+)', line)
        if m:
            vals[m.group(1)] = int(m.group(2), 16)
    return vals

C = consts()

def cstr(s):
    out = []
    for ch in s.encode('utf-8'):
        if ch == 0x22: out.append('\\"')
        elif ch == 0x5c: out.append('\\\\')
        elif ch == 0x0a: out.append('\\n')
        elif ch < 0x20 or ch >= 0x7f: out.append('\\x%02x""' % ch)
        else: out.append(chr(ch))
    return ('"' + ''.join(out) + '"').replace('??', '?\\?')

# ---------------------------------------------------------------- text

def parse_text_sources():
    """label -> decoded UTF-8 string."""
    texts = {}
    tdir = os.path.join(ROOT, 'src', 'text')
    for fn in sorted(os.listdir(tdir)):
        if not re.match(r'text\d+\.asm$', fn):
            continue
        label, buf, skip = None, None, 0
        for raw in open(os.path.join(tdir, fn), encoding='utf-8'):
            line = raw.rstrip('\n')
            code = re.sub(r';.*$', '', line) if '"' not in line else line
            s = code.strip()
            if not s:
                continue
            if s.startswith('IF ') or s == 'ENDC' or s.startswith('.'):
                continue
            m = re.match(r'^(\w+):$', s)
            if m:
                label, buf = m.group(1), []
                continue
            m = re.match(r'^(text|line|textfw|linefw|db)\s+(.*)$', s)
            if m:
                kind, rest = m.groups()
                strs = re.findall(r'"((?:[^"\\]|\\.)*)"', rest)
                txt = ''.join(strs)
                txt = txt.replace('<RAMNAME>', '\x09').replace('<RAMTEXT>', '\x0b').replace('<RAMNUM>', '\x0c')
                if kind in ('line', 'linefw'):
                    buf.append('\n')
                buf.append(txt)
                continue
            if s == 'done':
                texts[label] = ''.join(buf)
                label = None
                continue
            if s == 'half2full' or s.startswith('ds '):
                continue
            raise SystemExit(f'{fn}: unhandled text line {s!r}')
    return texts

def gen_text(rom):
    order = []
    for line in open(os.path.join(ROOT, 'src', 'text', 'text_offsets.asm')):
        m = re.match(r'^\s*textpointer\s+(\w+)', line)
        if m:
            order.append(m.group(1))
    texts = parse_text_sources()
    with open(os.path.join(GEN, 'text.h'), 'w') as f:
        f.write(HDR + '#ifndef TCG_GEN_TEXT_H\n#define TCG_GEN_TEXT_H\n\n')
        f.write('/* text ids, as produced by the `textpointer` macro (ldtx) */\nenum {\n\tNULL_TEXT = 0,\n')
        for i, n in enumerate(order, 1):
            f.write(f'\t{n} = 0x{i:04x},\n')
        f.write('};\n\n')
        f.write(f'#define NUM_TEXTS 0x{len(order) + 1:x}\n')
        f.write('/* UTF-8 strings; TX_RAM1 (0x09), TX_RAM2 (0x0b) and TX_RAM3 (0x0c) are kept as control bytes */\n')
        f.write('extern const char *const gTexts[NUM_TEXTS];\n\n#endif\n')
    with open(os.path.join(GEN, 'text.c'), 'w') as f:
        f.write(HDR + '#include "text.h"\n\nconst char *const gTexts[NUM_TEXTS] = {\n\t"",\n')
        for n in order:
            f.write(f'\t/* {n} */ {cstr(texts.get(n, ""))},\n')
        f.write('};\n')
    return order, texts

# ---------------------------------------------------------------- cards

def gen_cards(rom, text_order, texts):
    b, a = rom.addr('CardPointers')
    n = C['NUM_CARDS']
    L = C['PKMN_CARD_DATA_LENGTH']
    card_names = {}
    for line in open(os.path.join(ROOT, 'src', 'constants', 'card_constants.asm')):
        m = re.match(r'^\s*const\s+(\w+)\s*;\s*\$([0-9a-fA-F]+)', line)
        if m:
            card_names[int(m.group(2), 16)] = m.group(1)
    rows = []
    for cid in range(n + 1):
        ptr = rom.word(b, a + 2 * cid)
        data = bytearray()
        for i in range(L):
            addr = ptr + i
            # past the end of the ROMX window the CPU would read VRAM; model it as 0
            data.append(rom.byte(b, addr) if addr < 0x8000 else 0)
        label = rom.name_at(b, ptr) if ptr else 'NULL'
        tid = data[3] | data[4] << 8
        name = texts.get(text_order[tid - 1], '') if 0 < tid <= len(text_order) else ''
        rows.append((cid, card_names.get(cid, '?'), label, name, bytes(data), ptr))
    with open(os.path.join(GEN, 'cards.h'), 'w') as f:
        f.write(HDR + '#ifndef TCG_GEN_CARDS_H\n#define TCG_GEN_CARDS_H\n#include "common.h"\n\n')
        f.write('/* gCardData[id] = the PKMN_CARD_DATA_LENGTH bytes LoadCardDataToHL_FromCardID copies for card id.\n'
                ' * Non-Pokemon cards are shorter in ROM, so their tail holds the bytes of the following card,\n'
                ' * exactly like on the Game Boy. Card 0 (NULL pointer) reads ROM0 $0000. */\n')
        f.write('extern const u8 gCardData[NUM_CARDS + 1][PKMN_CARD_DATA_LENGTH];\n')
        f.write('/* original ROM address of each card record (bank $%02x), 0 for card 0 */\n' % b)
        f.write('extern const u16 gCardDataAddress[NUM_CARDS + 1];\n\n#endif\n')
    with open(os.path.join(GEN, 'cards.c'), 'w') as f:
        f.write(HDR + '#include "cards.h"\n\nconst u8 gCardData[NUM_CARDS + 1][PKMN_CARD_DATA_LENGTH] = {\n')
        for cid, const, label, name, data, ptr in rows:
            f.write(f'\t/* ${cid:02x} {const} ({label}) {name} */\n\t{{')
            f.write(', '.join(f'0x{x:02x}' for x in data))
            f.write('},\n')
        f.write('};\n\nconst u16 gCardDataAddress[NUM_CARDS + 1] = {\n')
        for i in range(0, len(rows), 8):
            f.write('\t' + ', '.join(f'0x{r[5]:04x}' for r in rows[i:i + 8]) + ',\n')
        f.write('};\n')
    return rows

# ---------------------------------------------------------------- decks

def gen_decks(rom):
    b, a = rom.addr('DeckPointers')
    nd = C['NUM_VALID_DECKS']
    decks = []
    for i in range(nd):
        ptr = rom.word(b, a + 2 * i)
        data = bytearray()
        p = ptr
        while True:
            cnt = rom.byte(b, p)
            data.append(cnt)
            if cnt == 0:
                # CopyDeckData also reads the two bytes after the terminator into wDeckName
                data.append(rom.byte(b, p + 1))
                data.append(rom.byte(b, p + 2))
                break
            data.append(rom.byte(b, p + 1))
            p += 2
        decks.append((i, rom.name_at(b, ptr), bytes(data)))
    names = {}
    for line in open(os.path.join(ROOT, 'src', 'constants', 'deck_constants.asm')):
        m = re.match(r'^\s*deck_const\s+(\w+)\s*;\s*\$([0-9a-fA-F]+)', line)
        if m:
            names[int(m.group(2), 16)] = m.group(1)
    with open(os.path.join(GEN, 'decks.h'), 'w') as f:
        f.write(HDR + '#ifndef TCG_GEN_DECKS_H\n#define TCG_GEN_DECKS_H\n#include "common.h"\n\n')
        f.write('/* DeckPointers: (count, card id) pairs terminated by 0 (plus the 2 ROM bytes that follow,\n * which CopyDeckData copies to wDeckName), indexed by *_DECK constants */\n')
        f.write('extern const u8 *const gDeckLists[NUM_VALID_DECKS];\n')
        f.write('extern const char *const gDeckLabels[NUM_VALID_DECKS];\n\n#endif\n')
    with open(os.path.join(GEN, 'decks.c'), 'w') as f:
        f.write(HDR + '#include "decks.h"\n\n')
        for i, label, data in decks:
            f.write(f'/* {names.get(i, "?")} */\nstatic const u8 {label}_{i}[] = {{')
            f.write(', '.join(f'0x{x:02x}' for x in data) + '};\n')
        f.write('\nconst u8 *const gDeckLists[NUM_VALID_DECKS] = {\n')
        for i, label, data in decks:
            f.write(f'\t{label}_{i},\n')
        f.write('};\n\nconst char *const gDeckLabels[NUM_VALID_DECKS] = {\n')
        for i, label, data in decks:
            f.write(f'\t"{label}",\n')
        f.write('};\n')

# ---------------------------------------------------------------- effect commands

def gen_effect_commands(rom):
    sec_bank, sec_start = rom.addr('EffectCommands')
    sec_end = 0x4f9b
    func_bank = 0x0b
    lists = []
    funcs = set()
    labels = sorted({(a, n) for (bk, a), ns in rom.by_addr.items() if bk == sec_bank and sec_start <= a <= sec_end
                     for n in ns if n.endswith('EffectCommands') and n != 'EffectCommands' and '.' not in n})
    for addr, name in labels:
        cmds = []
        p = addr
        while True:
            t = rom.byte(sec_bank, p)
            if t == 0:
                break
            fptr = rom.word(sec_bank, p + 1)
            fname = rom.name_at(func_bank, fptr)
            if fname is None:
                raise SystemExit(f'no symbol for effect function at {func_bank:02x}:{fptr:04x}')
            cmds.append((t, fname))
            funcs.add(fname)
            p += 3
        lists.append((addr, name, cmds))
    cmdnames = {v: k for k, v in C.items() if k.startswith('EFFECTCMDTYPE_')}
    with open(os.path.join(GEN, 'effect_commands.h'), 'w') as f:
        f.write(HDR + '#ifndef TCG_GEN_EFFECT_COMMANDS_H\n#define TCG_GEN_EFFECT_COMMANDS_H\n#include "common.h"\n\n')
        f.write('/* effect functions (engine/duel/effect_functions.asm); return value = carry flag */\n')
        for fn in sorted(funcs):
            f.write(f'bool {fn}(void);\n')
        f.write('\ntypedef bool (*EffectFunc)(void);\n')
        f.write('struct EffectCommand { u8 type; EffectFunc func; };\n')
        f.write('struct EffectCommandList { u16 address; const char *name; const struct EffectCommand *cmds; };\n')
        f.write(f'#define NUM_EFFECT_COMMAND_LISTS {len(lists)}\n')
        f.write('/* sorted by address (the value stored in card data and wLoadedAttackEffectCommands) */\n')
        f.write('extern const struct EffectCommandList gEffectCommandLists[NUM_EFFECT_COMMAND_LISTS];\n')
        f.write('struct EffectFunctionAddress { u16 address; EffectFunc func; };\n')
        f.write(f'#define NUM_EFFECT_FUNCTIONS {len(funcs)}\n')
        f.write('extern const struct EffectFunctionAddress gEffectFunctionsByAddress[NUM_EFFECT_FUNCTIONS];\n')
        f.write('#define EFFECT_FUNCTION_LIST(X) \\\n')
        for fn in sorted(funcs):
            f.write(f'\tX({fn}) \\\n')
        f.write('\n\n#endif\n')
    with open(os.path.join(GEN, 'effect_commands.c'), 'w') as f:
        f.write(HDR + '#include "effect_commands.h"\n\n')
        for addr, name, cmds in lists:
            f.write(f'static const struct EffectCommand {name}[] = {{\n')
            for t, fn in cmds:
                f.write(f'\t{{ {cmdnames.get(t, hex(t))}, {fn} }},\n')
            f.write('\t{ 0, 0 },\n};\n')
        f.write('\nconst struct EffectCommandList gEffectCommandLists[NUM_EFFECT_COMMAND_LISTS] = {\n')
        for addr, name, cmds in lists:
            f.write(f'\t{{ 0x{addr:04x}, "{name}", {name} }},\n')
        f.write('};\n')
    # effect functions by address, for command lists read from arbitrary memory
    func_addrs = sorted((rom.sym[fn][1], fn) for fn in funcs)
    with open(os.path.join(GEN, 'effect_functions_by_address.c'), 'w') as f:
        f.write(HDR + '#include "effect_commands.h"\n\n')
        f.write('/* every effect function referenced by a command list, sorted by its address in bank $0b */\n')
        f.write(f'const struct EffectFunctionAddress gEffectFunctionsByAddress[{len(func_addrs)}] = {{\n')
        for a, fn in func_addrs:
            f.write(f'\t{{ 0x{a:04x}, {fn} }},\n')
        f.write('};\n')
    # weak fallbacks so the engine links while effect functions are being ported
    with open(os.path.join(GEN, 'effect_stubs.c'), 'w') as f:
        f.write(HDR + '#include "effect_commands.h"\n\nvoid tcg_fatal(const char *msg);\n\n')
        f.write('#define STUB(name) __attribute__((weak)) bool name(void) { tcg_fatal("effect function not ported: " #name); return false; }\n')
        f.write('EFFECT_FUNCTION_LIST(STUB)\n')
    print(f'{len(lists)} effect command lists, {len(funcs)} effect functions')

# ---------------------------------------------------------------- ROM data blobs

def gen_rom_blobs(rom):
    """Raw ROM data that the engine reads through pointers stored in RAM (e.g. the
    AI card lists in wAICardList*). tools/rom_blobs.txt lists one label per line,
    optionally followed by a size; without a size the blob extends to the next
    label in the same bank."""
    cfg = os.path.join(ROOT, 'port', 'tools', 'rom_blobs.txt')
    entries = []
    if os.path.exists(cfg):
        for line in open(cfg):
            line = line.split('#')[0].strip()
            if not line:
                continue
            parts = line.split()
            label = parts[0]
            if label.startswith('@'):
                # a whole ROM bank: @<bank>
                bank = int(label[1:], 16)
                entries.append((bank, 0 if bank == 0 else 0x4000, 0x4000, f'BANK_{bank:02x}'))
                continue
            if label not in rom.sym:
                raise SystemExit(f'rom_blobs.txt: unknown label {label}')
            bank, addr = rom.sym[label]
            if len(parts) > 1:
                size = int(parts[1], 0)
            else:
                nxt = min([a for (b, a) in rom.by_addr if b == bank and a > addr] + [0x8000])
                size = nxt - addr
            entries.append((bank, addr, size, label))
    entries.sort()
    def cname(label):
        return 'blob_' + re.sub(r'\W', '_', label)
    with open(os.path.join(GEN, 'rom_blobs.h'), 'w') as f:
        f.write(HDR + '#ifndef TCG_GEN_ROM_BLOBS_H\n#define TCG_GEN_ROM_BLOBS_H\n#include "common.h"\n\n')
        f.write('/* raw ROM bytes of selected labels (tools/rom_blobs.txt), keyed by their original\n'
                ' * bank:address, for data the engine reaches through pointers stored in RAM. */\n')
        f.write('struct RomBlob { u8 bank; u16 address; u16 size; const char *label; const u8 *data; };\n')
        f.write(f'#define NUM_ROM_BLOBS {len(entries)}\n')
        f.write('extern const struct RomBlob gRomBlobs[NUM_ROM_BLOBS > 0 ? NUM_ROM_BLOBS : 1];\n')
        f.write('/* pointer to the byte at bank:address (inside a blob), or NULL */\n')
        f.write('const u8 *RomPtr(u8 bank, u16 address);\n')
        f.write('/* GB address of a label listed in rom_blobs.txt (0 if missing) */\n')
        f.write('u16 RomAddr(const char *label);\n\n#endif\n')
    with open(os.path.join(GEN, 'rom_blobs.c'), 'w') as f:
        f.write(HDR + '#include <string.h>\n#include "rom_blobs.h"\n\n')
        for bank, addr, size, label in entries:
            data = rom.read(bank, addr, size)
            f.write(f'/* {bank:02x}:{addr:04x} {label} */\nstatic const u8 {cname(label)}[] = {{')
            f.write(', '.join(f'0x{x:02x}' for x in data) + '};\n')
        f.write('\nconst struct RomBlob gRomBlobs[NUM_ROM_BLOBS > 0 ? NUM_ROM_BLOBS : 1] = {\n')
        for bank, addr, size, label in entries:
            f.write(f'\t{{ 0x{bank:02x}, 0x{addr:04x}, {size}, "{label}", {cname(label)} }},\n')
        if not entries:
            f.write('\t{ 0, 0, 0, "", 0 },\n')
        f.write('};\n\nconst u8 *RomPtr(u8 bank, u16 address)\n{\n'
                '\tfor (int i = 0; i < NUM_ROM_BLOBS; i++) {\n'
                '\t\tconst struct RomBlob *b = &gRomBlobs[i];\n'
                '\t\tif (b->bank == bank && address >= b->address && address < b->address + b->size)\n'
                '\t\t\treturn b->data + (address - b->address);\n'
                '\t}\n\treturn 0;\n}\n\n'
                'u16 RomAddr(const char *label)\n{\n'
                '\tfor (int i = 0; i < NUM_ROM_BLOBS; i++)\n'
                '\t\tif (!strcmp(gRomBlobs[i].label, label))\n'
                '\t\t\treturn gRomBlobs[i].address;\n'
                '\treturn 0;\n}\n')
    print(f'{len(entries)} rom blobs')

def gen_symbols(rom):
    cfg = os.path.join(ROOT, 'port', 'tools', 'symbols.txt')
    with open(os.path.join(GEN, 'symbols.h'), 'w') as f:
        f.write(HDR + '#ifndef TCG_GEN_SYMBOLS_H\n#define TCG_GEN_SYMBOLS_H\n\n')
        for line in open(cfg):
            line = line.split('#')[0].strip()
            if not line:
                continue
            b, a = rom.sym[line]
            name = re.sub(r'\W', '_', line)
            f.write(f'#define GBADDR_{name} 0x{a:04x} /* bank ${b:02x} */\n')
        f.write('\n#endif\n')

def main():
    rom = Rom()
    order, texts = gen_text(rom)
    gen_cards(rom, order, texts)
    gen_decks(rom)
    gen_effect_commands(rom)
    gen_rom_blobs(rom)
    gen_symbols(rom)
    print('ok')

if __name__ == '__main__':
    main()
