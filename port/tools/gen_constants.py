#!/usr/bin/env python3
"""Extract every numeric constant from the disassembly's constants/*.asm files
and emit them as C #defines (port/src/gen/constants.h).

Values are computed by rgbasm itself (PRINTLN), so they are exact. EQUS
constants that depend on WRAM labels (PLAYER_TURN, DUELVARS_*) are resolved
from the linked .sym file.
"""
import os, re, subprocess, sys, tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'src')
RGBASM = os.environ.get('RGBASM', 'rgbasm')

SKIP_FILES = {'hardware.inc', 'charmaps.asm'}

NAME_RES = [
    re.compile(r'^\s*DEF\s+(\w+)\s+(EQU|RB|RW|EQUS)\b(.*)$'),
    re.compile(r'^\s*(?:const|deck_const)\s+(\w+)'),
]

def load_sym():
    sym = {}
    with open(os.path.join(ROOT, 'poketcg.sym')) as f:
        for line in f:
            m = re.match(r'^([0-9a-f]{2}):([0-9a-f]{4}) (\S+)$', line.strip())
            if m:
                sym[m.group(3)] = (int(m.group(1), 16), int(m.group(2), 16))
    return sym

def collect_names():
    names, equs, order = [], {}, []
    # joypad constants from hardware.inc
    for line in open(os.path.join(SRC, 'constants', 'hardware.inc')):
        m = re.match(r'^\s*def\s+((?:B_)?PAD_\w+)\s+equ\b', line, re.I)
        if m:
            names.append(('hardware.inc', m.group(1)))
    # TX_SYMBOL tile constants (txsymbol macro in charmaps.asm)
    for line in open(os.path.join(SRC, 'constants', 'charmaps.asm')):
        m = re.match(r'^\s*txsymbol\s+"(\w+)"', line)
        if m:
            names.append(('charmaps.asm', 'SYM_' + m.group(1)))
    for fn in sorted(os.listdir(os.path.join(SRC, 'constants'))):
        if fn in SKIP_FILES or not fn.endswith('.asm'):
            continue
        with open(os.path.join(SRC, 'constants', fn)) as f:
            for line in f:
                line = line.split(';')[0]
                m = NAME_RES[0].match(line)
                if m:
                    if m.group(2) == 'EQUS':
                        equs[m.group(1)] = m.group(3).strip().strip('"')
                    else:
                        names.append((fn, m.group(1)))
                    continue
                m = NAME_RES[1].match(line)
                if m:
                    names.append((fn, m.group(1)))
                    if line.strip().startswith('deck_const'):
                        names.append((fn, m.group(1) + '_ID'))
    return names, equs

def main():
    names, equs = collect_names()
    sym = load_sym()
    with tempfile.TemporaryDirectory() as td:
        asm = os.path.join(td, 'c.asm')
        with open(asm, 'w') as f:
            f.write('INCLUDE "macros.asm"\nINCLUDE "constants.asm"\n')
            for fn, n in names:
                f.write(f'IF DEF({n})\nPRINTLN "{fn} {n} {{d:{n}}}"\nENDC\n')
        out = subprocess.run([RGBASM, '-I', SRC, '-o', os.devnull, asm],
                             capture_output=True, text=True, cwd=SRC)
        if out.returncode != 0:
            print(out.stderr, file=sys.stderr)
            sys.exit(1)
    values = {}
    by_file = {}
    for line in out.stdout.splitlines():
        fn, n, v = line.split()
        v = int(v)
        if -128 <= v < 0:
            v &= 0xff  # negative constants are used as 8-bit values (cp MENU_CANCEL)
        elif v < 0:
            v &= 0xffff
        if n in values or n in ('NULL',):
            continue
        values[n] = v
        by_file.setdefault(fn, []).append(n)
    # EQUS constants that reference labels
    for n, expr in equs.items():
        m = re.match(r'^(LOW|HIGH)\((\w+)\)$', expr)
        if m and m.group(2) in sym:
            addr = sym[m.group(2)][1]
            values[n] = addr & 0xff if m.group(1) == 'LOW' else addr >> 8
            by_file.setdefault('duel_constants.asm', []).append(n)
        elif expr.startswith('*'):
            continue  # unit-suffix macros like `palettes`
        else:
            try:
                py = re.sub(r'[A-Za-z_]\w*', lambda m: str(values[m.group(0)]), expr)
                values[n] = int(eval(py, {}, {}))
                by_file.setdefault('misc_equs', []).append(n)
            except Exception:
                print(f'warning: unhandled EQUS {n} = {expr}', file=sys.stderr)
    dst = os.path.join(ROOT, 'port', 'src', 'gen', 'constants.h')
    with open(dst, 'w') as f:
        f.write('/* Generated by port/tools/gen_constants.py from src/constants (asm). Do not edit. */\n')
        f.write('#ifndef TCG_GEN_CONSTANTS_H\n#define TCG_GEN_CONSTANTS_H\n\n')
        for fn in sorted(by_file):
            f.write(f'/* {fn} */\n')
            for n in by_file[fn]:
                f.write(f'#define {n} 0x{values[n]:x}\n')
            f.write('\n')
        f.write('#endif\n')
    print(f'wrote {len(values)} constants to {dst}')

if __name__ == '__main__':
    main()
