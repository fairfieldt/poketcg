#!/usr/bin/env python3
"""Extract exact card, starter, booster and auto-deck data from the linked ROM.

Generation requires poketcg.gbc + poketcg.sym. The checked-in C output does not.
"""
from pathlib import Path
import re
import sys

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
sys.path.insert(0,str(ROOT/'port/tools'))
from romsym import Rom

rom=Rom()
def addr(label): return rom.addr(label)
def read(label,n): return rom.read(*addr(label),n)
def deck(bank,pointer):
    cards=[]
    while True:
        count=rom.byte(bank,pointer);pointer+=1
        if not count:break
        card=rom.byte(bank,pointer);pointer+=1
        cards += [card]*count
    assert len(cards)>=30,len(cards)
    name=rom.word(bank,pointer)
    return (cards+[0]*60)[:60],name
def values(items): return ','.join(str(v) for v in items)

out=['/* Generated by port/gameplay/gen_data.py; do not edit. */','#include "../gameplay.h"','']
bank,base=addr('CardPointers')
out+=['const GpCard gp_cards[GP_NUM_CARDS+1] = {','    {0},']
for card in range(1,229):
    p=rom.word(bank,base+card*2)
    data=rom.read(bank,p,10)
    out.append('    {'+values([data[3]|data[4]<<8,data[0],data[5],data[6],data[9] if data[0]<8 else 255])+'},')
out+=['};','const GpDeck gp_preset_decks[55] = {']
bank,base=addr('DeckPointers')
for i in range(55):
    p=rom.word(bank,base+i*2)
    if p:
        cards,name=deck(bank,p)
    else:cards,name=[0]*60,0
    out.append('    {'+str(name)+',"",{'+values(cards)+'}},')
out+=['};','const GpRecipe gp_auto_recipes[GP_AUTO_RECIPES] = {']
bank,base=addr('AutoDeckMachineEntries')
for i in range(50):
    p=rom.word(bank,base+i*6)
    cards,_=deck(bank,p)
    out.append('    {'+values([rom.word(bank,base+i*6+2),rom.word(bank,base+i*6+4)])+',{'+values(cards)+'}},')
out+=['};','const GpBooster gp_boosters[GP_BOOSTERS] = {']
bank,base=addr('BoosterDataJumptable')
special={'GenerateRandomEnergy':1,'GenerateEnergyBoosterLightningFire':2,
         'GenerateEnergyBoosterWaterFighting':3,'GenerateEnergyBoosterGrassPsychic':4,'GenerateRandomEnergyBooster':5}
special_addr={rom.addr(label)[1]:mode for label,mode in special.items()}
rarity=list(read('BoosterSetRarityAmountsTable',16))
for i in range(29):
    p=rom.word(bank,base+i*2)
    data=list(rom.read(bank,p,12))
    energy=data[1]|data[2]<<8
    mode=special_addr.get(energy,0)
    assert mode or energy<256
    out.append('    {'+values([data[0],mode,energy if not mode else 0])+',{'+values(data[3:12])+'},{'+values(rarity[data[0]*4+1:data[0]*4+4])+'}},')
out+=['};','const uint8_t gp_challenge_decks[40] = {'+values(read('ChallengeMachine_OpponentDeckIDs',40))+'};',
      'const uint8_t gp_challenge_initial_name[16] = {'+values(read('ChallengeMachine_DrMasonText',16))+'};',
      'const uint8_t gp_mail_boosters[16][2] = {']
data=read('PCMailBoosterPacks',32)
out+=['    {'+values(data[i:i+2])+'},' for i in range(0,32,2)]
out+=['};','const uint16_t gp_mail_text[16][2] = {']
bank,base=addr('PCMailTextPages')
out+=['    {'+values([rom.word(bank,base+i*4),rom.word(bank,base+i*4+2)])+'},' for i in range(16)]
out+=['};','']
path=HERE/'gen/data.c'
path.write_text('\n'.join(out))
print(path)
