#!/usr/bin/env python3
"""Native script RAM addresses and card names from the linked disassembly."""
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[3]
sys.path.insert(0,str(ROOT/'port/tools'))
from romsym import Rom
rom=Rom()
fields=['wActiveGameEvent','wChallengeHallNPC','wConsole','wCurMap','wCurrentNPCNameTx','wDefaultSong','wDuelResult','wGiftCenterChoice','wLoadNPCDirection','wLoadNPCXPos','wLoadNPCYPos','wMultichoiceTextboxResult_ChooseDeckToDuelAgainst','wNPCDuelist','wPlayerDirection','wPlayerXCoord','wPlayerYCoord','wTempNPC','wTxRam2','wTxRam2_b','wTxRam3','wTxRam3_b','wd3d0','wd698']
widths={4:2,17:2,18:2,19:2,20:2,22:4}
lines=['/* Generated by tools/gen_native_fields.py. */','static const struct {const char *name; uint16_t address; uint8_t width;} native_fields[] = {']
for i,name in enumerate(fields):lines.append('{"'+name+'",'+str(rom.addr(name)[1])+','+str(widths.get(i,1))+'},')
lines+=['};','static const uint16_t native_card_names[229] = {0,']
b,p=rom.addr('CardPointers')
for i in range(1,229):lines.append(str(rom.word(b,rom.word(b,p+i*2)+3))+',')
lines+=['};']
(ROOT/'port/overworld/gen/native_fields.h').write_text('\n'.join(lines)+'\n')
