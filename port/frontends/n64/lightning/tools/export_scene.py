"""Export the editable .blend's tagged source meshes (including modifiers).

blender assets/lightning_club.blend -b --python tools/export_scene.py
The placed character previews share the source meshes and are not exported twice.
"""
import bpy
from collections import defaultdict
import json
from mathutils import Vector
from pathlib import Path
import struct

OUT=Path(__file__).resolve().parents[1]/'assets'

def export_scene():
    manifest=json.loads(bpy.context.scene['lightning_manifest'])
    textures=manifest['textures']
    batches=defaultdict(lambda:([],[],{}))
    light=Vector((-.3,.5,1)).normalized()
    depsgraph=bpy.context.evaluated_depsgraph_get()
    sources=sorted((o for o in bpy.context.scene.objects
                    if o.type=='MESH' and o.get('export_source',False)),key=lambda o:o.name)
    for source in sources:
        obj=source.evaluated_get(depsgraph)
        data=obj.to_mesh()
        data.calc_loop_triangles()
        assert data.uv_layers.active, f'{source.name}: UV layer required'
        pivot=tuple(source['pivot']) # original map X/south/height joint coordinates
        model,part=source['model'],source['part']
        for tri in data.loop_triangles:
            mat=data.materials[tri.material_index]
            tex=int(mat['texture_id'])
            assert -1<=tex<len(textures)
            vs,indices,cache=batches[(model,part,tex,pivot)]
            normal=(obj.matrix_world.to_3x3().inverted().transposed() @ tri.normal).normalized()
            shade=1 if tex>=0 else .68+.32*max(0,normal.dot(light))
            color=tuple(round(min(1,c*shade)*255) for c in mat.diffuse_color[:3])+(255,)
            for li in tri.loops:
                pos=obj.matrix_world @ data.vertices[data.loops[li].vertex_index].co
                uv=data.uv_layers.active.data[li].uv
                vertex=(pos.x-pivot[0],pos.z-pivot[2],-pos.y-pivot[1],uv.x,1-uv.y,*color)
                if vertex not in cache:
                    cache[vertex]=len(vs)
                    vs.append(vertex)
                indices.append(cache[vertex])
        obj.to_mesh_clear()
    with (OUT/'scene.l64').open('wb') as f:
        f.write(struct.pack('>4sHH',b'L643',len(batches),len(textures)))
        for name in textures:
            encoded=(name+'.sprite').encode()
            assert len(encoded)<32
            f.write(encoded.ljust(32,b'\0'))
        for (model,part,tex,pivot),(vs,indices,_) in sorted(batches.items()):
            assert 0<len(vs)<65536
            f.write(struct.pack('>HHhHII3f',model,part,tex,0,len(vs),len(indices),pivot[0],pivot[2],pivot[1]))
            for vertex in vs:
                f.write(struct.pack('>5f4B',*vertex))
            f.write(struct.pack('>'+str(len(indices))+'H',*indices))
            f.write(b'\0'*((-f.tell())%4))
    manifest.update(vertices=sum(len(b[0]) for b in batches.values()),
                    triangles=sum(len(b[1])//3 for b in batches.values()),batches=len(batches))
    (OUT/'scene.json').write_text(json.dumps(manifest,indent=2)+'\n')
    def cf(value): return f'{float(value):.6f}f'
    lines=['/* Generated by tools/export_scene.py. */','static const Actor lightning_npc_data[] = {']
    for actor in manifest['actors'][1:]:
        lines.append('    {'+str(actor['model'])+','+','.join(cf(actor[k]) for k in ('x','z','heading'))+'},')
    lines+=['};','static const float lightning_solids[][4] = {']
    lines+=['    {'+','.join(map(cf,r))+'},' for r in manifest['colliders']]
    lines+=['};']
    (OUT/'world_data.h').write_text('\n'.join(lines)+'\n')
    print('EXPORT',json.dumps({k:manifest[k] for k in ('vertices','triangles','batches')}))
    return manifest

if __name__=='__main__':
    export_scene()
