#!/usr/bin/env python3
"""Stage isolated character-model style options for the DIAGNOSTIC=18 preview.

The baseline option is derived from the production actor exports with their
model IDs rewritten to 1; production files are never modified. Each further
option directory holds <slug>/scene.l64, scene.json and textures/*.png.
"""
import argparse,json,shutil,struct,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parents[5]
GENERATED=ROOT/'port/world3d/generated'
SLUGS=('mark','dr_mason','ronald')


def rewrite_model(data,model):
    magic,batches,textures=struct.unpack_from('>4sHH',data,0);assert magic==b'L643'
    out=bytearray(data);pos=8+32*textures
    names=[data[8+32*i:8+32*i+32].split(b'\0')[0].decode() for i in range(textures)]
    for _ in range(batches):
        _m,part,tex,_r,nv,ni=struct.unpack_from('>HHhHII',data,pos)
        struct.pack_into('>H',out,pos,model)
        pos+=28+nv*24+ni*2;pos+=(-pos)%4
    assert pos==len(data),'Trailing L643 data'
    return bytes(out),names


def stage(output,option,slug,l64,png_dir,mksprite):
    base=output/option;(base/'maps').mkdir(parents=True,exist_ok=True);(base/'textures').mkdir(exist_ok=True)
    data,names=rewrite_model(l64.read_bytes(),1)
    (base/'maps'/f'actor_{slug}.l64').write_bytes(data)
    for name in names:
        png=png_dir/name.replace('.sprite','.png');assert png.is_file(),png
        if (base/'textures'/name).is_file():continue
        target=base/'textures'/png.name;shutil.copy2(png,target)
        subprocess.run([mksprite,'-f','RGBA16','-o',str(target.parent),str(target)],check=True,stdout=subprocess.DEVNULL)
        target.unlink()


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--options',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--header',type=Path,required=True)
    parser.add_argument('--mksprite',default='/opt/libdragon/bin/mksprite')
    args=parser.parse_args()
    if args.output.exists():shutil.rmtree(args.output)
    entries=[('baseline','Current')]
    for slug in SLUGS:
        stage(args.output,'baseline',slug,GENERATED/'maps'/f'actor_{slug}.l64',GENERATED/'textures',args.mksprite)
    if args.options.is_dir():
        for folder in sorted(p for p in args.options.iterdir() if p.is_dir() and (p/'option.json').is_file()):
            meta=json.loads((folder/'option.json').read_text())
            if not all((folder/slug/'scene.l64').is_file() for slug in SLUGS):continue
            for slug in SLUGS:
                stage(args.output,folder.name,slug,folder/slug/'scene.l64',folder/slug/'textures',args.mksprite)
            entries.append((folder.name,meta.get('label',folder.name)))
    lines=['/* Generated by tools/pack_model_options.py. */',f'#define OPTION_COUNT {len(entries)}',
           'static const char *const option_ids[]={'+','.join(f'"{i}"' for i,_ in entries)+'};',
           'static const char *const option_labels[]={'+','.join(f'"{l}"' for _,l in entries)+'};','']
    text='\n'.join(lines)
    if not args.header.exists() or args.header.read_text()!=text:
        args.header.parent.mkdir(parents=True,exist_ok=True);args.header.write_text(text)
    print('MODEL OPTIONS:',', '.join(i for i,_ in entries))


if __name__=='__main__':main()
