#!/usr/bin/env python3
"""Extract original CGB intro/title art and motion from the linked disassembly.

No image synthesis or screenshot capture: tilemaps, 2bpp graphics, palette
entries, OAM, and frame_data are decoded from poketcg.gbc/poketcg.sym using
the same source readers as port/maps. Normal N64 builds use checked-in PNGs.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[5]
sys.path.insert(0, str(ROOT / 'port/tools'))
sys.path.insert(0, str(ROOT / 'port/frontends/web/tools'))
import render_maps as maps
from png import read_png, write_png

OUT = ROOT / 'port/frontends/n64/adventure/assets/intro'


def save(path, pixels):
    write_png(path, len(pixels[0]), len(pixels),
              [bytes(channel for pixel in row for channel in pixel) for row in pixels])


def scene_vram(game, tileset, offset):
    bank, ptr, _ = game.gfx_entry(maps.GFXTABLE_TILESETS, tileset)
    count = game.rom.word(bank, ptr)
    data = game.rom.read(bank, ptr + 2, count * 16)
    vram = [bytearray(0x1800), bytearray(0x1800)]
    slots = [(0, 0x9000), (0, 0x8800), (1, 0x9000), (1, 0x8800)]
    if offset == 0x80:
        slots = slots[1:]
    position = 0
    for vb, address in slots:
        size = min(128, count - position)
        if size <= 0:
            break
        vram[vb][address - 0x8000:address - 0x8000 + size * 16] = data[position * 16:(position + size) * 16]
        position += size
    assert position == count
    return vram


def sprite(game, sprite_id, animation_id, palettes, palette_base=0):
    tiles = game.sprite_tiles(sprite_id)
    frame = game.anim_first_frame(animation_id)
    left = min(dx for dy, dx, t, a in frame)
    top = min(dy for dy, dx, t, a in frame)
    width = max(dx + 8 for dy, dx, t, a in frame) - left
    height = max(dy + 8 for dy, dx, t, a in frame) - top
    pixels = [[(0, 0, 0, 0)] * width for _ in range(height)]
    for dy, dx, tile_id, attributes in reversed(frame):
        tile = maps.decode_tile(tiles[tile_id])
        palette = palettes[(attributes & 7) + palette_base]
        for y in range(8):
            for x in range(8):
                index = tile[7-y if attributes & 0x40 else y][7-x if attributes & 0x20 else x]
                if index:
                    pixels[dy-top+y][dx-left+x] = (*palette[index], 255)
    return pixels, (left, top)


def motion(game):
    rom = game.rom
    animations = []
    for animation in range(191, 217):
        bank, ptr, _ = game.gfx_entry(maps.GFXTABLE_SPRITE_ANIMATIONS, animation)
        records = []
        ptr += 3  # frame_table: frame bank then table address
        for _ in range(4096):
            values = [maps.s8(v) for v in rom.read(bank, ptr, 4)]
            ptr += 4
            records.append(values)
            if values[1] == 0:
                break
        else:
            raise ValueError(f'Unterminated animation {animation}')
        animations.append(records)
    source = (ROOT / 'src/engine/sequences/intro_sequence_commands.asm').read_text()
    coordinates, ids = [], []
    for suffix in ('CharizardScene', 'ScytherScene', 'AerodactylScene', 'InitialTitleScreen', 'InTitleScreen'):
        block = source.split('IntroOrbCoordinates_' + suffix + ':', 1)[1].split('\n\n', 1)[0]
        xy = [[int(x), int(y)] for x, y in re.findall(r'db\s+(\d+),\s*(\d+)', block)]
        assert len(xy) == 7
        coordinates.append(xy)
        block = source.split('IntroOrbAnimations_' + suffix + ':', 1)[1].split('\n\n', 1)[0]
        sequence = [int(value) for value in re.findall(r'SPRITE_ANIM_(\d+)', block)]
        assert len(sequence) == 7
        ids.append(sequence)
    return animations, coordinates, ids


def header(animations, coordinates, animation_ids):
    lines = ['/* Generated by tools/build_intro.py from original frame_data. */',
             '#ifndef ADVENTURE_INTRO_ASSETS_H', '#define ADVENTURE_INTRO_ASSETS_H',
             '#include <stdint.h>',
             'typedef struct { int16_t frame, duration; int8_t dx, dy; } IntroAnimFrame;',
             'typedef struct { const IntroAnimFrame *frames; unsigned count; } IntroAnimation;',
             '/* Charizard, Scyther, Aerodactyl, title: palette0/color0. */',
             'static const uint8_t intro_clear_rgb[4][3] = {{231,231,198},{231,231,198},{231,231,198},{231,231,198}};']
    for number, frames in enumerate(animations, 191):
        lines.append(f'static const IntroAnimFrame intro_animation_{number}[] = {{')
        lines.extend(' {' + ','.join(map(str, frame)) + '},' for frame in frames)
        lines.append('};')
    lines.append('static const IntroAnimation intro_animations[26] = {')
    lines.extend(f' {{intro_animation_{number},sizeof(intro_animation_{number})/sizeof(IntroAnimFrame)}},' for number in range(191,217))
    lines.append('};')
    lines.append('static const uint8_t intro_orb_coordinates[5][7][2] = {')
    lines.extend(' {' + ','.join('{' + ','.join(map(str,pair)) + '}' for pair in stage) + '},' for stage in coordinates)
    lines.append('};')
    lines.append('static const uint8_t intro_orb_animation_ids[5][7] = {')
    lines.extend(' {' + ','.join(map(str, stage)) + '},' for stage in animation_ids)
    lines.extend(['};', '#endif', ''])
    return '\n'.join(lines)


def check(out):
    manifest = json.loads((out/'intro_assets.json').read_text())
    assert len(manifest['assets']) == 12
    for asset in manifest['assets']:
        path = out/(asset['name']+'.png')
        assert hashlib.sha256(path.read_bytes()).hexdigest() == asset['sha256'], path
        width, height, pixels, _ = read_png(path)
        assert (width,height) == (asset['width'],asset['height']), path
        colors = {pixel for row in pixels for pixel in row}
        assert len(colors) > 2, path
        if asset['name'].startswith('orb_') or asset['name'] == 'press_start':
            assert any(pixel[3] == 0 for pixel in colors), path
            assert any(pixel[3] == 255 for pixel in colors), path
        if asset['name'].startswith('orb_'):
            # The N64 adds a sampling gutter without altering these original
            # pixels. Its transparent RGB bleed uses this single outline color.
            assert (width,height) == (16,16), path
            opaque = [[bool(pixel[3]) for pixel in row] for row in pixels]
            assert all(opaque[y][x] == opaque[y][width-1-x] ==
                       opaque[height-1-y][x] for y in range(height) for x in range(width)), path
            outline = {pixels[y][x][:3] for y in range(height) for x in range(width)
                       if opaque[y][x] and any(nx < 0 or ny < 0 or nx >= width or ny >= height or
                                              not opaque[ny][nx] for nx,ny in
                                              ((x-1,y),(x+1,y),(x,y-1),(x,y+1)))}
            assert len(outline) == 1, path
    animations = manifest['animations']
    assert len(animations) == 26
    for frames in animations:
        assert frames[-1] == [0,0,0,0]
        assert len(frames) > 2
        assert all(-1 <= f[0] <= 1 and -1 <= f[1] <= 127 for f in frames)
    assert (out/'intro_assets.h').read_text() == header(animations,manifest['orb_coordinates'],manifest['orb_animation_ids'])
    print('INTRO ASSETS PASS: 12 original images, transparency/dimensions/hashes; 26 original animation tables')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, default=OUT)
    parser.add_argument('--check', action='store_true', help='Validate checked-in assets without a Game Boy ROM')
    args = parser.parse_args()
    if args.check:
        check(args.out)
        return
    args.out.mkdir(parents=True, exist_ok=True)
    game = maps.Game(str(ROOT))
    tc, pc = game.consts['tilemap_constants.asm'], game.consts['palette_constants.asm']
    sc, ac = game.consts['sprite_constants.asm'], game.consts['animation_constants.asm']
    assets = []
    for name in ('title', 'charizard', 'scyther', 'aerodactyl'):
        source = 'TITLE_SCREEN' if name == 'title' else name.upper() + '_INTRO'
        palette = 'PALETTE_TITLE_SCREEN' if name == 'title' else 'PALETTE_' + source + '_CGB'
        tilemap = game.load_tilemap(tc['TILEMAP_' + source + '_CGB'])
        pals, bgp, _ = game.bg_palettes([pc[palette]])
        image = maps.render_bg(tilemap, scene_vram(game, tilemap['tileset'], 0 if name == 'title' else 0x80), pals, bgp)
        # Scene_... loads intro panels at tile (6,3). Outside the panel is
        # palette0 from InitMenuScreen; index0 is the original warm white.
        if name == 'title':
            pixels = [[(*pixel,255) for pixel in row] for row in image.px]
        else:
            pixels = [[(231,231,198,255)] * 160 for _ in range(144)]
            for y, row in enumerate(image.px):
                pixels[y+24][48:112] = [(*pixel,255) for pixel in row]
        path = args.out/(name+'.png')
        save(path, pixels)
        assets.append(dict(name=name,width=160,height=144,source_tilemap=source+'_CGB',source_palette=palette))
    palettes = game.obj_palettes(pc['PALETTE_TITLE_SCREEN_ORBS'])
    for index, name in enumerate(('grass','fire','water','colorless','lightning','psychic','fighting')):
        pixels, offset = sprite(game,sc['SPRITE_'+name.upper()],ac['SPRITE_ANIM_192'],palettes,index)
        save(args.out/('orb_'+name+'.png'), pixels)
        assets.append(dict(name='orb_'+name,width=len(pixels[0]),height=len(pixels),offset=offset))
    pixels, offset = sprite(game,sc['SPRITE_PRESS_START'],ac['SPRITE_ANIM_191'],palettes)
    save(args.out/'press_start.png', pixels)
    assets.append(dict(name='press_start',width=len(pixels[0]),height=len(pixels),offset=offset,origin=[40,96]))
    animations, coordinates, animation_ids = motion(game)
    (args.out/'intro_assets.h').write_text(header(animations,coordinates,animation_ids))
    for asset in assets:
        asset['sha256'] = hashlib.sha256((args.out/(asset['name']+'.png')).read_bytes()).hexdigest()
    manifest = dict(format='CGB original intro/title',assets=assets,animations=animations,orb_coordinates=coordinates,orb_animation_ids=animation_ids,
                    sequence_source='src/data/sequences/intro.asm',sprite_source='src/data/duel/animations/anims3.asm + anims4.asm',
                    background_fade_frames=16,panel_wait_frames=[[44,44,30],[44,44,30],[44,100,60]],press_start_frames=[37,26])
    (args.out/'intro_assets.json').write_text(json.dumps(manifest,indent=2)+'\n')
    check(args.out)
    print(f'INTRO ASSETS PASS: {len(assets)} original images; {len(animations)} source animations; {args.out}')


if __name__ == '__main__':
    main()
