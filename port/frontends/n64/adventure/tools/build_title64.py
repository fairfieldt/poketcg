#!/usr/bin/env python3
"""Pack the generated transparent title artwork at the two native sizes."""
import argparse
from collections import deque
import hashlib
import json
from pathlib import Path
from PIL import Image

ADV=Path(__file__).resolve().parents[1]
OUT=ADV/'assets/title64'
REFERENCE=ADV/'assets/intro/title.png'

def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()

def resize_logo(source,size):
    # Resample premultiplied RGB/alpha, then return to straight-alpha storage.
    # Hidden source RGB cannot darken the partially transparent outline.
    image=source.convert('RGBa').resize(size,Image.Resampling.LANCZOS).convert('RGBA')
    width,height=size;pixels=[image.getpixel((x,y)) for y in range(height) for x in range(width)]
    known=[p[3]!=0 for p in pixels];queue=deque(i for i,value in enumerate(known) if value)
    # RDP bilinear filtering sees RGB even in zero-alpha texels. Extend the
    # neighboring edge colors without changing alpha or any visible pixel.
    while queue:
        i=queue.popleft();x=i%width;y=i//width
        for nx,ny in ((x-1,y),(x+1,y),(x,y-1),(x,y+1)):
            if nx<0 or ny<0 or nx>=width or ny>=height:continue
            j=ny*width+nx
            if known[j]:continue
            pixels[j]=(*pixels[i][:3],0);known[j]=True;queue.append(j)
    image.putdata(pixels);return image

def header():
    return '''/* Generated by tools/build_title64.py. Original intro art stays separate. */
#ifndef ADVENTURE_TITLE64_ASSETS_H
#define ADVENTURE_TITLE64_ASSETS_H
enum {TITLE64_LEFT=20,TITLE64_TOP=12,TITLE64_WIDTH=280,TITLE64_HEIGHT=140};
#define TITLE64_LOGO_320 "rom:/title64/logo-320.sprite"
#define TITLE64_LOGO_480 "rom:/title64/logo-480.sprite"
#endif
'''

def test_resampling():
    # Same visible red shape, different hidden background colors. Both must
    # produce the identical stored derivative, including bled transparent RGB.
    a=Image.new('RGBA',(16,16),(0,0,0,0));b=Image.new('RGBA',(16,16),(0,255,0,0))
    for y in range(4,12):
        for x in range(4,12):a.putpixel((x,y),(220,32,16,255));b.putpixel((x,y),(220,32,16,255))
    aa=resize_logo(a,(7,7));bb=resize_logo(b,(7,7));assert aa.tobytes()==bb.tobytes()
    assert any(aa.getpixel((x,y))[3] not in (0,255) for y in range(7) for x in range(7))
    for y in range(7):
        for x in range(7):
            r,g,blue,alpha=aa.getpixel((x,y))
            if alpha>=128:assert r>210 and g<40 and blue<24

def check(out):
    data=json.loads((out/'manifest.json').read_text());assert sha(out/'source.png')==data['source_sha256']
    assert sha(out/'prompt.txt')==data['prompt_sha256'] and sha(REFERENCE)==data['original_reference_sha256']
    source=Image.open(out/'source.png').convert('RGBA');assert list(source.size)==data['source_size']
    assert list(source.getbbox())==data['source_visible_bbox']
    assert data['title']=='Pokémon Trading Card Game 64'
    for width,size in ((320,(280,140)),(480,(420,210))):
        path=out/f'logo-{width}.png';asset=data['assets'][str(width)];image=Image.open(path).convert('RGBA')
        assert image.size==size and sha(path)==asset['sha256']
        assert image.tobytes()==resize_logo(source,size).tobytes(),'Derivative differs from premultiplied source'
        assert 0 in image.getchannel('A').getextrema() and image.getchannel('A').getextrema()[1]==255
        assert any(any(image.getpixel((x,y))[:3]) for y in range(size[1]) for x in range(size[0]) if image.getpixel((x,y))[3]==0)
        scale=width/320;assert 20*scale+size[0]<=width and 12*scale+size[1]<=153*scale
    assert (out/'title64_assets.h').read_text()==header()
    test_resampling();print('TITLE64 ASSETS PASS: generated title,280x140/420x210 native derivatives, premultiplied resize/edge bleed, original footer reference unchanged')

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--out',type=Path,default=OUT);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    if args.check:check(args.out);return
    source=Image.open(args.out/'source.png').convert('RGBA');assets={}
    for width,size in ((320,(280,140)),(480,(420,210))):
        path=args.out/f'logo-{width}.png';image=resize_logo(source,size);image.save(path)
        assets[str(width)]={'file':path.name,'size':list(size),'sha256':sha(path),'rgba16_bytes':size[0]*size[1]*2}
    (args.out/'title64_assets.h').write_text(header())
    data={'title':'Pokémon Trading Card Game 64','provenance':'Built-in image_gen edit/reference generation; exact prompt in prompt.txt',
      'source_sha256':sha(args.out/'source.png'),'prompt_sha256':sha(args.out/'prompt.txt'),'source_size':list(source.size),'source_visible_bbox':list(source.getbbox()),
      'original_reference':'../intro/title.png','original_reference_sha256':sha(REFERENCE),'processing':'Premultiplied LANCZOS downsample, straight-alpha storage, nearest edge RGB in zero-alpha pixels; no redrawing',
      'runtime':'Only the selected derivative is loaded; source.png is excluded from the ROM','assets':assets}
    (args.out/'manifest.json').write_text(json.dumps(data,indent=2,ensure_ascii=False)+'\n');check(args.out)

if __name__=='__main__':main()
