#!/usr/bin/env python3
"""Extract every original glossary topic and credits text/scene/NPC placement."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[5]
OUT=Path(__file__).resolve().parents[1]/'extra_data.h'
values={}
for file in ['port/src/gen/constants.h','port/src/gen/text.h']:
 for name,value in re.findall(r'(?:#define\s+)?(\w+)\s*(?:=|\s)\s*(0x[0-9a-fA-F]+|\d+)\b',(ROOT/file).read_text()):
  values[name]=int(value,0)
def val(s):return values.get(s,int(s,0) if s.isdigit() else 0)
def npc(s):
 x,y,d,id=[a.strip() for a in s.split(',')]
 return [val(id),val(x),val(y),val(d)]
credits=(ROOT/'src/data/sequences/credits.asm').read_text()
source=(ROOT/'src/engine/sequences/credits_sequence_commands.asm').read_text()
club_lists=[]
for match in re.finditer(r'^\.CreditsNPCs_\w+\n(.*?)(?=^\.CreditsNPCs_|^; bc = coordinates)',source,re.S|re.M):
 rows=[]
 for args in re.findall(r'^\s*db\s+([^;\n]+)',match[1],re.M):
  parts=[v.strip() for v in args.split(',')]
  if len(parts)==4:rows.append([val(v) for v in parts])
 club_lists.append(rows)
assert len(club_lists)==10,len(club_lists)
entries=[];mapid=0;club=255;npcs=[]
for raw in credits.splitlines():
 line=raw.split(';')[0].strip()
 if line.startswith('credits_seq_load_ow_map '):
  mapid=val(line.split(',')[-1].strip());club=255;npcs=[]
 elif line.startswith('credits_seq_load_club_map '):
  club=int(line.split()[-1]);mapid=0;npcs=[]
 elif line.startswith(('credits_seq_load_booster ','credits_seq_load_scene ')):
  mapid=0;club=255;npcs=[]
 elif line.startswith('credits_seq_load_npc '):npcs.append(npc(line.split(' ',1)[1]))
 elif line.startswith('credits_seq_print_text '):
  label=line.split(',')[-1].strip();assert label in values,label
  entries.append([values[label],mapid,club,list(npcs)])
assert len(entries)>=30,len(entries)
lines=['/* Generated by tools/gen_extra_ui.py from original sources. */',
 'typedef struct {uint8_t id,x,y,dir;} CreditNpc;',
 'typedef struct {uint16_t text;uint8_t map,club,count;CreditNpc npcs[8];} CreditEntry;',
 'static const uint16_t glossary[18][2] = {']
glossary=(ROOT/'src/engine/menus/glossary.asm').read_text()
rows=re.findall(r'^\s*glossary_entry\s+\d+,\s*(\w+),\s*(\w+)',glossary,re.M)
assert len(rows)==18
lines+=['{'+str(values[a])+','+str(values[b])+'},' for a,b in rows]
lines+=['};','static const uint8_t credit_club_maps[10]={6,9,12,15,18,21,24,27,30,32};',
 'static const CreditNpc credit_club_npcs[10][8]={']
for row in club_lists:lines.append('{'+','.join('{'+','.join(map(str,n))+'}' for n in row)+'},')
lines+=['};','static const uint8_t credit_club_counts[10]={'+','.join(str(len(row)) for row in club_lists)+'};',
 'static const CreditEntry credit_entries[] = {']
for text,mapid,club,npcs in entries:
 lines.append('{'+','.join(map(str,[text,mapid,club,len(npcs)]))+',{'+','.join('{'+','.join(map(str,n))+'}' for n in npcs)+'}},')
lines+=['};','']
OUT.write_text('\n'.join(lines))
print(f'{len(rows)} glossary topics; {len(entries)} credit entries;10 clubscenes; {OUT}')
