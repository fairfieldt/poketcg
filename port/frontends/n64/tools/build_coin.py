#!/usr/bin/env python3
"""Decode the original CGB Pikachu coin for the native and web duel UIs."""
from pathlib import Path
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[4]
sys.path[:0] = [str(ROOT/'port/tools'), str(ROOT/'port/frontends/n64/adventure/tools')]
import render_maps as maps
from build_intro import sprite, save

game = maps.Game(str(ROOT))
sc, ac, pc = (game.consts[n+'_constants.asm'] for n in ('sprite', 'animation', 'palette'))
palettes = game.obj_palettes(pc['PALETTE_COIN'])
out = ROOT/'port/assets/ui/coin'
web = ROOT/'port/frontends/web/src/img'
out.mkdir(parents=True, exist_ok=True)
lines = ['/* Original CGB coin tiles/OAM/palette; generated by tools/build_coin.py. */',
         '#ifndef TCGN64_COIN_ART_H', '#define TCGN64_COIN_ART_H', '#include <stdint.h>',
         'enum { COIN_ART_W=24, COIN_ART_H=24 };',
         'static const uint16_t coin_art[2][COIN_ART_W*COIN_ART_H] = {']
outputs = []
# core.asm chooses animation170 (Pikachu) for e=HEADS and171 for e=TAILS;
# its DUEL_ANIM_COIN_HEADS/TAILS labels themselves are reversed at that call.
for name, animation in (('tails',171), ('heads',170)):
    pixels, offset = sprite(game, sc['SPRITE_DUEL_COIN'], ac['SPRITE_ANIM_'+str(animation)], palettes)
    assert len(pixels) == 24 and len(pixels[0]) == 24 and offset == (-12,-12)
    save(out/(name+'.png'), pixels)
    save(web/('coin-'+name+'.png'), pixels)
    values = [((r>>3)<<11)|((g>>3)<<6)|((b>>3)<<1)|(a>=128) for row in pixels for r,g,b,a in row]
    lines.append(' {')
    lines.extend(','.join(f'0x{v:04x}' for v in values[y*24:(y+1)*24])+',' for y in range(24))
    lines.append(' },')
    outputs.append(dict(name=name,animation=animation,offset=offset,dimensions=[24,24],
                        sha256=hashlib.sha256((out/(name+'.png')).read_bytes()).hexdigest()))
lines += ['};','#endif','']
(ROOT/'port/frontends/n64/coin_art.h').write_text('\n'.join(lines))
(out/'manifest.json').write_text(json.dumps(dict(source='src/gfx/duel/anims/coin.png + original OAM and CoinPal',
    result_mapping='src/engine/duel/core.asm .done_toss_anim: e=HEADS selects animation170, TAILS171',
    source_sha256=hashlib.sha256((ROOT/'src/gfx/duel/anims/coin.png').read_bytes()).hexdigest(),
    format='native RGBA5551; web RGBA PNG; original 24x24 pixels',outputs=outputs),indent=2)+'\n')
print('COIN ART PASS: original Pikachu heads and plain tails, 24x24, native + web')
