#!/usr/bin/env python3
"""Rasterize 14px and 21px antialiased banner fonts into four-bit coverage masks.

Uses Pillow's bundled scalable default font, rather than shipping a system font
file. Native draw code blends the masks into its existing 16-bit UI canvas.
"""
from pathlib import Path
import math
from PIL import Image,ImageDraw,ImageFont

ROOT=Path(__file__).resolve().parents[1]
SCALE=4
WIDTH,HEIGHT=16,18
font=ImageFont.load_default(size=14*SCALE)
masks=[];advances=[]
for value in range(32,127):
    char=chr(value)
    bbox=font.getbbox(char,anchor='la',stroke_width=1)
    assert bbox[0]+SCALE>=0 and bbox[1]>=0
    assert bbox[2]+SCALE<=WIDTH*SCALE and bbox[3]<=HEIGHT*SCALE,(char,bbox)
    image=Image.new('L',(WIDTH*SCALE,HEIGHT*SCALE))
    ImageDraw.Draw(image).text((SCALE,0),char,font=font,fill=255,stroke_width=1,anchor='la')
    image=image.resize((WIDTH,HEIGHT),Image.Resampling.LANCZOS)
    coverage=[max(0,min(15,round(image.getpixel((x,y))*15/255))) for y in range(HEIGHT) for x in range(WIDTH)]
    masks.append([(coverage[i]<<4)|coverage[i+1] for i in range(0,len(coverage),2)])
    advances.append(max(1,math.ceil(font.getlength(char)/SCALE)))
lines=['/* Generated by tools/build_banner_font.py; four-bit glyph coverage. */',
       '#ifndef TCGN64_BANNER_FONT_H','#define TCGN64_BANNER_FONT_H','#include <stdint.h>',
       f'enum {{ BANNER_FONT_FIRST=32, BANNER_FONT_WIDTH={WIDTH}, BANNER_FONT_HEIGHT={HEIGHT} }};',
       'static const uint8_t banner_font_advance[95] = {',
       ','.join(map(str,advances)),'};',
       f'static const uint8_t banner_font_coverage[95][{WIDTH*HEIGHT//2}] = {{']
for mask in masks:
    lines.append('{'+','.join(f'0x{v:02x}' for v in mask)+'},')
lines += ['};', 'enum { BANNER_HI_WIDTH=24, BANNER_HI_HEIGHT=27 };',
          'static const uint8_t banner_hi_coverage[95][324] = {']
font_hi=ImageFont.load_default(size=84)
for value in range(32,127):
    image=Image.new('L',(24*SCALE,27*SCALE))
    ImageDraw.Draw(image).text((6,0),chr(value),font=font_hi,fill=255,stroke_width=2,anchor='la')
    image=image.resize((24,27),Image.Resampling.LANCZOS)
    coverage=[max(0,min(15,round(image.getpixel((x,y))*15/255))) for y in range(27) for x in range(24)]
    mask=[(coverage[i]<<4)|coverage[i+1] for i in range(0,len(coverage),2)]
    lines.append('{'+','.join(f'0x{value:02x}' for value in mask)+'},')
lines+=['};','#endif']
(ROOT/'banner_font.h').write_text('\n'.join(lines)+'\n')
print('Banner font:',len(masks),'glyphs; 14px',sum(map(len,masks))+len(advances),'bytes, 21px',95*324,'bytes')
