#!/usr/bin/env python3
"""Build an original 11px duel face from Pillow's bundled Aileron font.

Pillow's default scalable font is Aileron Regular by Sora Sagano,
marked No Rights Reserved (https://dotcolon.net/fonts/aileron/).
No Nintendo font assets are used. Coverage is stored at four bits per pixel;
the one-quarter-pixel stroke keeps TV-size stems decisive without doubling.
The renderer measures advances in pixels and retains the compact bench face.
"""
from pathlib import Path
import math
from PIL import Image, ImageDraw, ImageFont
ROOT = Path(__file__).resolve().parents[1]
SCALE = 4
WIDTH, HEIGHT = 12, 12
font = ImageFont.load_default(size=11*SCALE)
masks, advances = [], []
for value in range(32, 127):
    glyph = chr(value)
    image = Image.new('L', (WIDTH*SCALE, HEIGHT*SCALE))
    ImageDraw.Draw(image).text((2, -3*SCALE), glyph, font=font, fill=255,
                              stroke_width=1, anchor='la')
    image = image.resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS)
    values = [max(0, min(15, round(image.getpixel((x,y))*15/255)))
              for y in range(HEIGHT) for x in range(WIDTH)]
    masks.append([(values[i] << 4) | values[i+1] for i in range(0,len(values),2)])
    advances.append(max(2, math.ceil(font.getlength(glyph)/SCALE)))
lines = ['/* Generated by tools/build_body_font.py; Pillow Aileron by Sora Sagano (No Rights Reserved). */',
         '#ifndef TCGN64_BODY_FONT_H', '#define TCGN64_BODY_FONT_H', '#include <stdint.h>',
         f'enum {{ BODY_FONT_FIRST=32, BODY_FONT_WIDTH={WIDTH}, BODY_FONT_HEIGHT={HEIGHT} }};',
         'static const uint8_t body_font_advance[95] = {', ','.join(map(str, advances)), '};',
         f'static const uint8_t body_font_coverage[95][{WIDTH*HEIGHT//2}] = {{']
for mask in masks:
    lines.append('{'+','.join(f'0x{value:02x}' for value in mask)+'},')
lines += ['};', '#endif']
(ROOT/'body_font.h').write_text('\n'.join(lines)+'\n')
print(f'Body font: {len(masks)} glyphs, {sum(map(len,masks))+len(advances)} bytes')
