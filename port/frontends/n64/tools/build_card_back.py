#!/usr/bin/env python3
"""Derive the published international Pokémon TCG back for both frontends.

No lettering or artwork is reconstructed. Source bytes/provenance are retained
in port/assets/ui/card-back. Native images are opaque RGBA5551 except rounded
outer corners; the renderer writes them into its existing cached CPU canvas.
"""
from pathlib import Path
import hashlib,json
from PIL import Image,ImageDraw
ROOT=Path(__file__).resolve().parents[3]
ASSET=ROOT/'assets/ui/card-back'
N64=ROOT/'frontends/n64'
WEB=ROOT/'frontends/web/src/img'
source=ASSET/'source.jpg'
image=Image.open(source).convert('RGBA')
# The official-art JPEG uses white outside its rounded card silhouette.
# Preserve the printed image and give only those outer corners transparency.
mask=Image.new('L',image.size,0)
ImageDraw.Draw(mask).rounded_rectangle((0,0,image.width-1,image.height-1),radius=36,fill=255)
image.putalpha(mask)
outputs=[]
masters={}
lines=['/* Generated by tools/build_card_back.py from the published card-back artwork.',
       ' * Pokémon TCG artwork © The Pokémon Company / Nintendo / Creatures / GAME FREAK.',
       ' * See ../../assets/ui/card-back/manifest.json for source and transformations. */',
       '#ifndef TCGN64_CARD_BACK_H','#define TCGN64_CARD_BACK_H','#include <stdint.h>']
for name,width,height in [('small',24,34),('standard',32,44),('small_hi',36,51),('high',48,66)]:
    if name in ('small_hi','high'):
        # Pokemon portraits retain their 64x48 GBC texels at 480x360 and expand
        # them by 1.5, rather than inventing extra image detail. Match that
        # texture scale for backs too, while keeping the rounded silhouette.
        resized=masters['small' if name=='small_hi' else 'standard'].resize((width,height),Image.Resampling.NEAREST)
        resized.putalpha(image.resize((width,height),Image.Resampling.LANCZOS).getchannel('A'))
    else:
        resized=image.resize((width,height),Image.Resampling.LANCZOS)
    values=[((r>>3)<<11)|((g>>3)<<6)|((b>>3)<<1)|(a>=128) for r,g,b,a in (resized.getpixel((x,y)) for y in range(height) for x in range(width))]
    native=Image.new('RGBA',(width,height))
    native.putdata([(((v>>11)&31)*255//31,((v>>6)&31)*255//31,((v>>1)&31)*255//31,255 if v&1 else 0) for v in values])
    masters[name]=native
    filename=ASSET/f'native-{name}.png';native.save(filename)
    lines += [f'enum {{ CARD_BACK_{name.upper()}_W={width}, CARD_BACK_{name.upper()}_H={height} }};',
              f'static const uint16_t card_back_{name}[{width*height}] = {{']
    for row in range(height):lines.append(','.join(f'0x{v:04x}' for v in values[row*width:(row+1)*width])+',')
    lines+=['};']
    outputs.append({'path':str(filename.relative_to(ROOT.parent)),'size':[width,height],'format':'RGBA5551','bytes':2*len(values),'sha256':hashlib.sha256(filename.read_bytes()).hexdigest()})
lines+=['#endif']
(N64/'card_back.h').write_text('\n'.join(lines)+'\n')
# Browser portraits also use the source GBC texels. Keep the existing file size
# and smooth corner mask, but share the faithful 32x44 color master with N64.
web=masters['standard'].resize((256,357),Image.Resampling.NEAREST)
web.putalpha(image.resize((256,357),Image.Resampling.LANCZOS).getchannel('A'))
WEB.mkdir(parents=True,exist_ok=True);web.save(WEB/'card-back.png')
outputs.append({'path':str((WEB/'card-back.png').relative_to(ROOT.parent)),'size':list(web.size),'format':'RGBA8 PNG','sha256':hashlib.sha256((WEB/'card-back.png').read_bytes()).hexdigest()})
manifest={
 'description':'International English-language Pokémon TCG card back: original yellow logos, Poké Ball and blue/white swirl.',
 'source':{'file':'source.jpg','url':'https://archives.bulbagarden.net/media/upload/1/17/Cardback.jpg','page':'https://archives.bulbagarden.net/wiki/File:Cardback.jpg','permanent_page':'https://archives.bulbagarden.net/w/index.php?title=File:Cardback.jpg&oldid=1200019','retrieved':'2026-10-31','size':list(image.size),'sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'published_revision':'2024-03-22 14:47 UTC','uploader':'C.Ezra.M','file_history_credit':'From Alternative Play Handbook; credit to JP from pkmncards.com.'},
 'official_reference':{'rules_page':'https://play.pokemon.com/en-gb/resources/rules/','handbook':'https://www.pokemon.com/static-assets/content-assets/cms2/pdf/trading-card-game/tcg-alternative-play-handbook-en.pdf','provenance_note':'The official Rules & Formats page links this handbook. The Bulbagarden file history identifies the handbook as its source; the JPEG here is the exact published Bulbagarden file, not a new PDF extraction.'},
 'rights':'Pokémon TCG artwork © The Pokémon Company / Nintendo / Creatures / GAME FREAK. Copyrighted artwork; no free-content license is asserted.',
 'transforms':['Retain original downloaded JPEG bytes.','Mask white outer corners with a 36px rounded rectangle at source resolution.','Derive unchanged 24x34/32x44 color masters from the original source with Lanczos; no recoloring, invented lettering, or reconstructed artwork.','Expand those masters with nearest-neighbor sampling to 36x51/48x66 at 480x360, matching the 1.5x texel scale of Pokemon portraits.','Keep each target resolution\'s original rounded alpha mask.','Native variants quantize RGB to five bits and alpha to one bit.','Web art expands the same 32x44 color master to the existing 256x357 file dimensions.'],
 'logical_color_masters':{'small':[24,34],'standard':[32,44]},
 'outputs':outputs,'native_total_bytes':sum(o.get('bytes',0) for o in outputs)}
(ASSET/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('Card backs:',manifest['native_total_bytes'],'native bytes; web',web.size,'source',image.size)
