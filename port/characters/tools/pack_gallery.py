#!/usr/bin/env python3
"""Pack each unique native export once for an on-device model viewer."""
import json
from pathlib import Path
import struct
import sys
sys.path.insert(0,str(Path(__file__).resolve().parent))
from validate import ROOT,read_mesh

catalog=json.loads((ROOT/'catalog.json').read_text())
entries=[];textures=[];all_batches=[]
for family in catalog['families']:
    folder=ROOT/'assets/models'/family['slug']
    paths=[folder/'scene.l64']+sorted(folder.glob('variants/*/scene.l64'))+sorted(folder.glob('poses/*/scene.l64'))+sorted(folder.glob('components/*/scene.l64'))
    for path in paths:
        info=json.loads(path.with_suffix('.json').read_text())
        name=info['appearance']
        if info.get('pose','standing')!='standing':name+='_'+info['pose']
        if info.get('component'):name+='_'+info['component']
        index=len(entries)+1
        entries.append(dict(name=name,id=index,path=str(path.relative_to(ROOT)),triangles=info['triangles']))
        local=info['textures']
        for t in local:
            if t not in textures:textures.append(t)
        for b in read_mesh(path):
            tex=textures.index(local[b['texture']]) if b['texture']>=0 else -1
            all_batches.append(dict(b,model=index,texture=tex))
gallery=ROOT/'gallery/assets';gallery.mkdir(parents=True,exist_ok=True)
with (gallery/'scene.l64').open('wb') as out:
    out.write(struct.pack('>4sHH',b'L643',len(all_batches),len(textures)))
    for t in textures:out.write((t+'.sprite').encode().ljust(32,b'\0'))
    for b in all_batches:
        vertices,indices=b['vertices'],b['indices']
        out.write(struct.pack('>HHhHII3f',b['model'],b['part'],b['texture'],0,len(vertices),len(indices),*b['pivot']))
        for v in vertices:out.write(struct.pack('>5f4B',*v))
        out.write(struct.pack('>'+str(len(indices))+'H',*indices))
        out.write(b'\0'*((-out.tell())%4))
(gallery/'gallery.json').write_text(json.dumps(dict(entries=entries,textures=textures,batches=len(all_batches)),indent=2)+'\n')
lines=['/* Generated by tools/pack_gallery.py. */','static const char *model_names[] = {']
lines += [json.dumps(e['name'])+',' for e in entries]
lines += ['};','#define MODEL_COUNT (sizeof(model_names)/sizeof(model_names[0]))']
(gallery/'models.h').write_text('\n'.join(lines)+'\n')
print('GALLERY',len(entries),'exports,',len(all_batches),'batches,',len(textures),'textures,',(gallery/'scene.l64').stat().st_size,'mesh bytes')
